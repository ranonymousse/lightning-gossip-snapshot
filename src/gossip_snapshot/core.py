"""Pinned Bitcoin Core as the chain backend: install, run and query it locally.

No download or node operation occurs on import or in tests. The node keeps the
full chain, listens for RPC on loopback only, has no wallet and accepts no
inbound peers.
"""

import base64
import fcntl
import hashlib
import json
import os
import platform
import shutil
import subprocess
import tarfile
import time
import urllib.error
import urllib.request
from pathlib import Path

from .common import GIB, MIB, PROJECT, save, sha256_file, utc_now
from .schema import load_json

DEFAULT_DIRECTORY = Path.home() / ".local/state/gossip-snapshot/bitcoin-core"
# Loopback RPC port of this node, apart from Bitcoin Core's default 8332. The LND
# configuration template names the same port.
RPC_PORT = 11332
# Bitcoin Core's RPC server: the threads that serve calls, and the calls that may wait for
# one. LND validates every announced channel through this interface while the collector
# and the audits query it as well.
RPC_THREADS = 16
RPC_WORK_QUEUE = 256
RPC_SECONDS = 120  # Time limit of one RPC call.
# A shorter limit while the node starts or stops, when it may not answer at all.
LIFECYCLE_RPC_SECONDS = 30
BINARIES = ("bitcoind", "bitcoin-cli")
MACHINES = {"x86_64": "x86_64-linux-gnu", "aarch64": "aarch64-linux-gnu"}
# A download that grows beyond this is cut off before it can fill the disk.
MAX_ARCHIVE_BYTES = 256 * MIB
DOWNLOAD_SECONDS = 60  # Time limit for the connection and for each read of the download.
# Free disk that an installation requires. Bitcoin Core reported about 892 GB of block
# files in November 2026.
MIN_FREE_GB = 900
DBCACHE_GB = 16  # Database cache written to the configuration. A start can override it.
# Blocks by which a synchronized node may trail its best known header: the header of a
# new block arrives before the block is validated.
HEADER_LEAD_BLOCKS = 2
START_SECONDS = 600  # Wait for a starting node to answer RPC calls.
STOP_SECONDS = 3600  # A large cache takes long to write at shutdown.
LAUNCH = "launch.json"
# Bitcoin Core's error code while it warms up: the node is loading and will answer later.
WARMING_UP = -28
CONFIG = """\
# Generated by gossip core install. Mainnet with the full chain, loopback RPC,
# no wallet and no inbound peers. A changed file blocks further use.
server=1
prune=0
txindex=0
disablewallet=1
listen=0
rpcbind=127.0.0.1
rpcallowip=127.0.0.1
rpcport={port}
rpcthreads={threads}
rpcworkqueue={queue}
dbcache={dbcache}
"""


class RPCError(ValueError):
    """An error that Bitcoin Core returned for a call, with its numeric code."""

    def __init__(self, code, message):
        super().__init__(f"Bitcoin Core RPC error {code}: {message}")
        self.code = code


def cache_mib(dbcache_gb):
    """A database cache size in MiB, the unit of Bitcoin Core's dbcache option, from GiB."""
    if not 1 <= dbcache_gb <= 64:
        raise ValueError("database cache must be between 1 and 64 GiB")
    return round(dbcache_gb * 1024)


def release(project=PROJECT, system=None, machine=None):
    """The pinned release archive for this machine: version, name, URL and SHA-256."""
    versions = load_json(project / "versions.json")
    target = MACHINES.get(machine or platform.machine())
    if (system or platform.system()) != "Linux" or target is None:
        raise ValueError("Bitcoin Core is installed on Linux only (x86_64 or aarch64)")
    version = versions["bitcoin_core_version"]
    name = f"bitcoin-{version}-{target}.tar.gz"
    url = versions["bitcoin_core_url"].format(version=version) + name
    return version, name, url, versions["bitcoin_core_sha256"][name]


def download(url, target, expected, progress=None):
    """Stream to a new private file and accept it only with the pinned hash."""
    digest, size = hashlib.sha256(), 0
    with (
        urllib.request.urlopen(url, timeout=DOWNLOAD_SECONDS) as response,
        target.open("xb") as stream,
    ):
        total = int(response.headers.get("Content-Length") or 0)
        while chunk := response.read(MIB):
            size += len(chunk)
            if size > MAX_ARCHIVE_BYTES:
                raise ValueError("release archive is larger than expected")
            digest.update(chunk)
            stream.write(chunk)
            if progress:
                progress(size, total)
    if digest.hexdigest() != expected:
        raise ValueError("release archive does not match the pinned SHA-256")


def install(
    directory,
    project=PROJECT,
    *,
    min_free_gb=MIN_FREE_GB,
    dbcache_gb=DBCACHE_GB,
    fetch=download,
    progress=None,
):
    """Install the pinned release in a new private directory and write the node's configuration.

    Returns the record saved as core.json, against which `verify` checks every later use.
    A failed installation leaves no directory behind.
    """
    if directory.exists() or directory.is_symlink():
        raise ValueError("Bitcoin Core directory already exists; choose a new --dir")
    if directory.resolve().is_relative_to(project.resolve()):
        raise ValueError("keep the chain data outside this checkout")
    dbcache = cache_mib(dbcache_gb)
    version, name, url, expected = release(project)
    directory.parent.mkdir(parents=True, exist_ok=True)
    free = shutil.disk_usage(directory.parent).free
    if free < min_free_gb * GIB:
        raise ValueError(
            f"{free / GIB:.0f} GiB free, but the full chain needs at least {min_free_gb:g} GiB"
        )
    directory.mkdir(mode=0o700)
    directory.chmod(0o700)
    try:
        for part in ("bin", "data"):
            (directory / part).mkdir(mode=0o700)
        archive = directory / name
        fetch(url, archive, expected, progress)
        with tarfile.open(archive) as tar:
            for binary in BINARIES:
                member = tar.getmember(f"bitcoin-{version}/bin/{binary}")
                if not member.isfile():
                    raise ValueError(f"release archive holds no regular {binary}")
                with (
                    tar.extractfile(member) as source,
                    (directory / "bin" / binary).open("xb") as out,
                ):
                    shutil.copyfileobj(source, out)
                (directory / "bin" / binary).chmod(0o500)
        archive.unlink()
        config = directory / "bitcoin.conf"
        config.write_text(
            CONFIG.format(port=RPC_PORT, threads=RPC_THREADS, queue=RPC_WORK_QUEUE, dbcache=dbcache)
        )
        config.chmod(0o600)
        record = {
            "schema_version": 1,
            "created_at": utc_now(),
            "version": version,
            "archive": name,
            "archive_sha256": expected,
            "binary_sha256": {b: sha256_file(directory / "bin" / b) for b in BINARIES},
            "config_sha256": sha256_file(config),
            "rpc_port": RPC_PORT,
            "platform": platform.platform(),
        }
        save(directory / "core.json", record)
    except BaseException:
        # Only the directory created above, and only before any chain data exists.
        shutil.rmtree(directory, ignore_errors=True)
        raise
    return record


def verify(directory):
    """Check that an installation is private and that its configuration and binaries are unchanged.

    Returns the installation record.
    """
    try:
        stat = directory.lstat()
    except FileNotFoundError:
        raise ValueError("Bitcoin Core is not installed; use ./run.sh core install") from None
    if directory.is_symlink() or stat.st_uid != os.getuid() or stat.st_mode & 0o077:
        raise ValueError(
            "Bitcoin Core directory must be owned by this user, private (0700), and not a link"
        )
    record = load_json(directory / "core.json")
    if sha256_file(directory / "bitcoin.conf") != record["config_sha256"]:
        raise ValueError("Bitcoin Core configuration changed; do not use it for collection")
    for binary in BINARIES:
        if sha256_file(directory / "bin" / binary) != record["binary_sha256"][binary]:
            raise ValueError(f"Bitcoin Core binary changed: {binary}")
    return record


class Client:
    """Loopback JSON-RPC with the node's cookie. The cookie is never logged or kept."""

    def __init__(self, directory, timeout=RPC_SECONDS, *, exact_amounts=False):
        self.directory, self.timeout = directory, timeout
        self.exact_amounts = exact_amounts
        # No environment proxy may ever receive the RPC credentials.
        self.opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))

    def __call__(self, method, *params):
        """Call one RPC method and return its result. An error reply raises RPCError."""
        try:
            cookie = (self.directory / "data/.cookie").read_text().strip()
        except OSError:
            raise ValueError("Bitcoin Core is not running (no RPC cookie)") from None
        body = {"jsonrpc": "1.0", "id": "gossip", "method": method, "params": list(params)}
        request = urllib.request.Request(
            f"http://127.0.0.1:{RPC_PORT}/",
            data=json.dumps(body).encode(),
            headers={
                "Content-Type": "application/json",
                "Authorization": "Basic " + base64.b64encode(cookie.encode()).decode(),
            },
        )
        try:
            with self.opener.open(request, timeout=self.timeout) as response:
                data = response.read()
        except urllib.error.HTTPError as exc:
            data = exc.read()  # Core reports RPC errors as JSON with an HTTP error status.
        except (urllib.error.URLError, OSError) as exc:
            reason = getattr(exc, "reason", exc)
            raise ValueError(f"Bitcoin Core RPC is unreachable: {reason}") from None
        try:
            if self.exact_amounts:
                from decimal import Decimal

                reply = json.loads(data, parse_float=Decimal)
            else:
                reply = json.loads(data)
        except ValueError:
            raise ValueError("Bitcoin Core RPC returned no JSON reply") from None
        if reply.get("error"):
            raise RPCError(reply["error"].get("code"), reply["error"].get("message"))
        return reply["result"]


def running(directory):
    """Bitcoin Core holds a POSIX lock on its data directory while it runs."""
    try:
        with (directory / "data/.lock").open("r+b") as stream:
            try:
                fcntl.lockf(stream, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except OSError:
                return True
            fcntl.lockf(stream, fcntl.LOCK_UN)
    except FileNotFoundError:
        pass
    return False


def launch(directory):
    """How the collector last started the node, or None when no start is on record."""
    path = directory / LAUNCH
    return load_json(path) if path.is_file() else None


def status(directory, client=None):
    """What the node reports about itself: not running, warming up, or its chain and peers."""
    record = verify(directory)
    if not running(directory):
        return {"running": False, "installed_version": record["version"]}
    client = client or Client(directory)
    try:
        chain, network = client("getblockchaininfo"), client("getnetworkinfo")
        states = client("getchainstates")["chainstates"]
    except RPCError as exc:
        if exc.code != WARMING_UP:
            raise
        return {"running": True, "warming_up": str(exc), "installed_version": record["version"]}
    return {
        "running": True,
        "installed_version": record["version"],
        "core_json_sha256": sha256_file(directory / "core.json"),
        "launch": launch(directory),
        # The node's own figure, so a cache override is confirmed rather than assumed.
        "coins_cache_bytes": sum(state.get("coins_tip_cache_bytes", 0) for state in states),
        "checked_at": utc_now(),
        "chain": chain["chain"],
        "blocks": chain["blocks"],
        "headers": chain["headers"],
        "best_block_hash": chain["bestblockhash"],
        "verification_progress": chain["verificationprogress"],
        "initial_block_download": chain["initialblockdownload"],
        "pruned": chain["pruned"],
        "size_on_disk": chain["size_on_disk"],
        "connections": network["connections"],
        "version": network["version"],
        "subversion": network["subversion"],
    }


def preflight(directory, client=None):
    """A collection session needs a running, complete, unpruned mainnet node."""
    info = status(directory, client)
    if not info["running"] or "warming_up" in info:
        raise ValueError(
            "Bitcoin Core is not ready; use ./run.sh core start and ./run.sh core status"
        )
    if info["chain"] != "main":
        raise ValueError("Bitcoin Core is not on mainnet")
    if info["pruned"]:
        raise ValueError("Bitcoin Core is pruned; funding-block lookups need the full chain")
    if info["initial_block_download"] or info["headers"] - info["blocks"] > HEADER_LEAD_BLOCKS:
        raise ValueError(
            f"Bitcoin Core is still synchronizing ({info['blocks']} of {info['headers']} blocks)"
        )
    return info


def start(directory, *, dbcache_gb=None, wait=START_SECONDS, client=None):
    """Start the node unless it runs. A cache override applies to this run only."""
    record = verify(directory)
    override = None if dbcache_gb is None else cache_mib(dbcache_gb)
    if running(directory):
        if override is not None:
            raise ValueError(
                "Bitcoin Core is already running; use ./run.sh core stop first, "
                "then start it with the new cache"
            )
    else:
        # Command-line options override bitcoin.conf, which stays as generated.
        arguments = [
            f"-datadir={directory / 'data'}",
            f"-conf={directory / 'bitcoin.conf'}",
            "-daemon",
        ]
        if override is not None:
            arguments.append(f"-dbcache={override}")
        # The daemon detaches itself. Its output goes to data/debug.log.
        subprocess.run(
            [str(directory / "bin/bitcoind"), *arguments],
            check=True,
            stdin=subprocess.DEVNULL,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            start_new_session=True,
        )
        save(
            directory / LAUNCH,
            {
                "schema_version": 1,
                "started_at": utc_now(),
                "config_sha256": record["config_sha256"],
                "dbcache_override_mib": override,
            },
        )
    client = client or Client(directory, timeout=LIFECYCLE_RPC_SECONDS)
    deadline = time.monotonic() + wait
    while True:
        try:
            client("getblockcount")
            return status(directory, client)
        except RPCError as exc:
            if exc.code != WARMING_UP:
                raise
        except ValueError:
            pass  # RPC not listening yet.
        if time.monotonic() >= deadline:
            raise ValueError(f"Bitcoin Core did not answer; inspect {directory / 'data/debug.log'}")
        time.sleep(2)


def stop(directory, *, wait=STOP_SECONDS, client=None):
    """Ask the node to stop over RPC and wait for its final cache write. No signal is ever sent."""
    verify(directory)
    if not running(directory):
        return False
    client = client or Client(directory, timeout=LIFECYCLE_RPC_SECONDS)
    asked = False
    deadline = time.monotonic() + wait
    while running(directory):
        if not asked:
            try:
                client("stop")
                asked = True
            except RPCError as exc:
                if exc.code != WARMING_UP:
                    raise
            except ValueError:
                # The RPC closes before the cache is written, so an earlier stop
                # is still at work. A node that is only starting gets asked again.
                pass
        if time.monotonic() >= deadline:
            raise ValueError(
                "Bitcoin Core has not stopped yet. Writing a large cache can take long. "
                "Leave it alone and repeat ./run.sh core stop"
            )
        time.sleep(1)
    return True
